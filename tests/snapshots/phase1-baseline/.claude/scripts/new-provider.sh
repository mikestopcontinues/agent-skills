#!/bin/bash
# Scaffold a new provider adapter package.
# Usage: new-provider.sh <name>
# Example: new-provider.sh perplexity → packages/provider-perplexity/

set -euo pipefail

NAME="${1:?Usage: new-provider.sh <name>}"

# Validate name: lowercase alphanumeric and hyphens only
if [[ ! "$NAME" =~ ^[a-z][a-z0-9-]*$ ]]; then
  echo "Error: name must be lowercase alphanumeric with hyphens (e.g. 'perplexity', 'open-router')" >&2
  exit 1
fi

ROOT=$(git rev-parse --show-toplevel)
PKG_DIR="$ROOT/packages/provider-${NAME}"

if [ -d "$PKG_DIR" ]; then
  echo "Error: $PKG_DIR already exists" >&2
  exit 1
fi

# Convert kebab-case name to PascalCase (e.g. "open-router" → "OpenRouter")
PASCAL=$(echo "$NAME" | sed 's/-/ /g' | awk '{for(i=1;i<=NF;i++) $i=toupper(substr($i,1,1)) substr($i,2)} 1' | sed 's/ //g')

echo "Scaffolding @os/provider-${NAME} (${PASCAL})..."

mkdir -p "$PKG_DIR/src/__fixtures__"
touch "$PKG_DIR/src/__fixtures__/.gitkeep"

# Helper: pipe a single-quoted heredoc through sed to replace placeholders.
# Single-quoted heredoc delimiters prevent shell expansion of backticks and $,
# so JS template literals pass through verbatim.
apply_template() {
  sed "s/__NAME__/${NAME}/g; s/__PASCAL__/${PASCAL}/g" > "$1"
}

