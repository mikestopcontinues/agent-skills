// Classify __PASCAL__ HTTP errors into typed ProviderError.
// Generated by new-provider.sh — customize error parsing for the provider.

import type {ErrorType} from '@os/errors';

import {ErrorTypes, ProviderError, withRetryableError} from '@os/errors';

const PROVIDER = '__NAME__';

/** __PASCAL__ error response body shape. */
interface __PASCAL__ErrorBody {
  message?: string;
  error?: {message?: string};
}

/** Classify an HTTP error response from __PASCAL__ into a ProviderError. */
export function classifyError(status: number, body: unknown): ProviderError {
  const message = parseErrorBody(body) ?? `__PASCAL__ API error (${status})`;
  const type = classifyStatusCode(status);

  const error = new ProviderError(message, {
    type,
    statusCode: status,
    provider: PROVIDER,
    raw: body,
  });

  return isRetryableType(type) ? withRetryableError(error) : error;
}

/** Classify a network/fetch error into a ProviderError. */
export function classifyNetworkError(error: unknown): ProviderError {
  if (error instanceof ProviderError) {
    return error;
  }

  const isAbort = error instanceof DOMException && error.name === 'AbortError';

  if (isAbort) {
    return new ProviderError('Request was aborted', {
      type: ErrorTypes.USER_ABORT,
      provider: PROVIDER,
      cause: error,
    });
  }

  const message = error instanceof Error ? error.message : String(error);
  const isTimeout = (/ETIMEDOUT|timeout/iu).test(message);

  return withRetryableError(new ProviderError(message, {
    type: isTimeout ? ErrorTypes.PROVIDER_TIMEOUT : ErrorTypes.PROVIDER_NETWORK,
    provider: PROVIDER,
    cause: error instanceof Error ? error : undefined,
  }));
}

// --- Internal ---

function classifyStatusCode(status: number): ErrorType {
  switch (status) {
    case 401: // falls through
    case 403: {
      return ErrorTypes.PROVIDER_AUTH;
    }

    case 408: {
      return ErrorTypes.PROVIDER_TIMEOUT;
    }

    case 429: {
      return ErrorTypes.PROVIDER_RATE_LIMIT;
    }

    default: {
      return status >= 500 ? ErrorTypes.PROVIDER_OVERLOAD : ErrorTypes.UNKNOWN;
    }
  }
}

function isRetryableType(type: ErrorType): boolean {
  return (
    type === ErrorTypes.PROVIDER_RATE_LIMIT ||
    type === ErrorTypes.PROVIDER_OVERLOAD ||
    type === ErrorTypes.PROVIDER_TIMEOUT
  );
}

function parseErrorBody(body: unknown): string | undefined {
  if (typeof body !== 'object' || body === null) {
    return undefined;
  }

  const obj = body as __PASCAL__ErrorBody;

  if (typeof obj.message === 'string') {
    return obj.message;
  }

  if (typeof obj.error?.message === 'string') {
    return obj.error.message;
  }

  return undefined;
}
