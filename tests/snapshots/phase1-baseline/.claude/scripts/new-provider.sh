/**
 * TextModel backed by the __PASCAL__ API.
 * @see create__PASCAL__Model
 */
export class __PASCAL__Model implements TextModel {
  readonly providerName: string = PROVIDER;
  readonly modelName: string;
  readonly #config: AdapterConfig;
  readonly #defaults: TextModelDefaults | undefined;

  constructor(modelName: string, config: AdapterConfig, defaults?: TextModelDefaults) {
    this.modelName = modelName;
    this.#config = config;
    this.#defaults = defaults;
  }

  async invoke(request: TextModelRequest): Promise<TextModelInvokeResult> {
    const merged = this.#defaults ? mergeDefaults(this.#defaults, request) : request;
    const body = buildRequestBody(this.modelName, merged);
    const headers = await authHeaders(this.#config);
    const response = await doFetch(
      {url: `${this.#config.baseUrl}/v1/chat`, headers, body, signal: merged.options?.signal},
      classifyNetworkError,
      classifyError,
    );

    return parseResponse(response as Record<string, unknown>, this.modelName);
  }

  async stream(request: TextModelRequest): Promise<TextModelStreamResult> {
    const merged = this.#defaults ? mergeDefaults(this.#defaults, request) : request;
    const body = buildRequestBody(this.modelName, merged, true);
    const headers = await authHeaders(this.#config);
    const rawStream = await doStreamFetch(
      {url: `${this.#config.baseUrl}/v1/chat`, headers, body, signal: merged.options?.signal},
      classifyNetworkError,
      classifyError,
      PROVIDER,
    );

    const streamGen = parse__PASCAL__Stream(rawStream, this.modelName);

    const wrappedStream = (async function *streamEvents(): AsyncGenerator<ProviderStreamEvent, TextModelInvokeResult, void> {
      let iterResult = await streamGen.next();

      while (!iterResult.done) {
        yield iterResult.value;
        iterResult = await streamGen.next();
      }

      return iterResult.value;
    }());

    return createTextModelStreamResult(wrappedStream);
  }
}

